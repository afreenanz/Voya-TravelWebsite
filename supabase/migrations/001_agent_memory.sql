-- Persistent travel preferences + conversation history for the AI travel agent.
-- Run AFTER supabase/schema.sql. Idempotent: safe to run more than once.
-- Supabase → SQL Editor → New query → paste → Run.

-- ── user_preferences: one row per user, long-lived preferences only ────────
-- Trip-specific details (dates, this trip's budget) live in the conversation's
-- draft itinerary, NOT here. The backend only writes allow-listed keys.
create table if not exists public.user_preferences (
  user_id     uuid primary key references public.users (id) on delete cascade,
  preferences jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now(),
  constraint user_preferences_is_object check (jsonb_typeof(preferences) = 'object')
);

-- ── conversations: one chat thread with the agent ─────────────────────────
create table if not exists public.conversations (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references public.users (id) on delete cascade,
  title           text not null default 'New conversation',
  draft_itinerary jsonb,            -- the itinerary currently being planned/edited
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists conversations_user_updated_idx
  on public.conversations (user_id, updated_at desc);

-- ── conversation_messages ──────────────────────────────────────────────────
create table if not exists public.conversation_messages (
  id              bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations (id) on delete cascade,
  role            text not null check (role in ('user', 'assistant')),
  content         text not null,
  tool_metadata   jsonb,            -- which tools ran and their status (no secrets)
  created_at      timestamptz not null default now()
);
create index if not exists conversation_messages_conv_idx
  on public.conversation_messages (conversation_id, id);

-- ── Security: same model as the existing tables ────────────────────────────
-- Only the Flask backend (service role) touches these tables; it scopes every
-- query to the signed-in user. RLS with no policies + revoked grants blocks
-- the public anon/publishable key entirely.
alter table public.user_preferences      enable row level security;
alter table public.conversations         enable row level security;
alter table public.conversation_messages enable row level security;
grant select, insert, update, delete
  on public.user_preferences, public.conversations, public.conversation_messages to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on public.user_preferences, public.conversations, public.conversation_messages
  from anon, authenticated;
