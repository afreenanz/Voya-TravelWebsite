-- Voya database schema (Supabase / Postgres).
-- Safe to run on a fresh project AND on the existing one: every statement is
-- idempotent (IF NOT EXISTS / ON CONFLICT), nothing is dropped.
-- Run it in Supabase → SQL Editor → New query → Run.

create extension if not exists pgcrypto;

-- ── users ──────────────────────────────────────────────────────────────────
create table if not exists public.users (
  id               uuid primary key default gen_random_uuid(),
  name             text,
  email            text not null,
  password_hash    text,
  full_name        text,
  phone            text,
  home_airport     text,
  preferred_budget text,
  travel_style     text,
  bio              text,
  avatar_url       text,
  created_at       timestamptz not null default now()
);
alter table public.users add column if not exists name             text;
alter table public.users add column if not exists password_hash    text;
alter table public.users add column if not exists full_name        text;
alter table public.users add column if not exists phone            text;
alter table public.users add column if not exists home_airport     text;
alter table public.users add column if not exists preferred_budget text;
alter table public.users add column if not exists travel_style     text;
alter table public.users add column if not exists bio              text;
alter table public.users add column if not exists avatar_url       text;
alter table public.users add column if not exists created_at       timestamptz not null default now();
-- One account per email (the backend lower-cases emails before writing).
create unique index if not exists users_email_key on public.users (email);

-- ── trips ──────────────────────────────────────────────────────────────────
create table if not exists public.trips (
  id             bigint generated by default as identity primary key,
  user_email     text not null,
  destination    text not null,
  cities         text,
  flag           text,
  budget         text,
  days           int,
  start_date     text,
  end_date       text,
  travelers      int,
  travel_style   text,
  status         text not null default 'planning',
  gradient       text,
  itinerary_json jsonb,
  created_at     timestamptz not null default now()
);
alter table public.trips add column if not exists cities         text;
alter table public.trips add column if not exists flag           text;
alter table public.trips add column if not exists budget         text;
alter table public.trips add column if not exists days           int;
alter table public.trips add column if not exists start_date     text;
alter table public.trips add column if not exists end_date       text;
alter table public.trips add column if not exists travelers      int;
alter table public.trips add column if not exists travel_style   text;
alter table public.trips add column if not exists gradient       text;
alter table public.trips add column if not exists itinerary_json jsonb;
alter table public.trips add column if not exists created_at     timestamptz not null default now();
create index if not exists trips_user_email_idx on public.trips (user_email);

-- ── searches (recent searches on the dashboard) ────────────────────────────
create table if not exists public.searches (
  id          bigint generated by default as identity primary key,
  user_email  text not null,
  destination text not null,
  created_at  timestamptz not null default now()
);
alter table public.searches add column if not exists destination text;
alter table public.searches add column if not exists created_at  timestamptz not null default now();
-- Older versions stored the search text in "query"; keep old rows readable.
do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'searches' and column_name = 'query') then
    alter table public.searches alter column query drop not null;
    update public.searches set destination = query where destination is null;
  end if;
end $$;
create index if not exists searches_user_email_idx on public.searches (user_email, created_at desc);

-- ── Normalise emails to lower case (the backend always looks them up lower-cased)
update public.trips    set user_email = lower(user_email) where user_email <> lower(user_email);
update public.searches set user_email = lower(user_email) where user_email <> lower(user_email);
do $$
begin
  -- Only lower-case user emails if that can't create duplicate accounts.
  if not exists (select lower(email) from public.users group by lower(email) having count(*) > 1) then
    update public.users set email = lower(email) where email <> lower(email);
  else
    raise notice 'Some users differ only by email case — merge them manually, then re-run.';
  end if;
end $$;

-- ── Row Level Security ─────────────────────────────────────────────────────
-- The Flask backend is the only client and uses the service-role key, which
-- bypasses RLS. Enabling RLS with NO policies blocks the public anon /
-- publishable key from reading or writing these tables (including
-- users.password_hash) through Supabase's REST API.
alter table public.users    enable row level security;
alter table public.trips    enable row level security;
alter table public.searches enable row level security;
-- ── Table privileges ───────────────────────────────────────────────────────
-- Only the backend's service role may touch these tables. The public roles
-- (anon / authenticated = publishable key) get nothing, on top of RLS.
grant usage on schema public to service_role;
grant select, insert, update, delete on public.users, public.trips, public.searches to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on public.users, public.trips, public.searches from anon, authenticated;

-- Legacy table from the removed "saved places" feature, if present.
do $$
begin
  if to_regclass('public.bookmarks') is not null then
    execute 'alter table public.bookmarks enable row level security';
  end if;
end $$;

